CREATE TABLE IF NOT EXISTS residents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    contact VARCHAR(20) NOT NULL,
    address VARCHAR(100) NOT NULL,
    area VARCHAR(100) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('Active', 'Pending'))
);

CREATE TABLE IF NOT EXISTS accounts (
    username VARCHAR(32) PRIMARY KEY,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN', 'RESIDENT')),
    resident_id BIGINT UNIQUE REFERENCES residents(id),
    CHECK ((role = 'ADMIN' AND resident_id IS NULL) OR (role = 'RESIDENT' AND resident_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS community_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module VARCHAR(24) NOT NULL,
    resident_id BIGINT REFERENCES residents(id),
    payload CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revision INT NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS idx_community_module_resident ON community_records(module, resident_id);
CREATE INDEX IF NOT EXISTS idx_community_resident ON community_records(resident_id);

CREATE TABLE IF NOT EXISTS activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(100) NOT NULL,
    action VARCHAR(400) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS portal_settings (
    id INT PRIMARY KEY CHECK (id = 1),
    community VARCHAR(100) NOT NULL,
    barangay VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS resident_notification_reads (
    resident_id BIGINT NOT NULL REFERENCES residents(id) ON DELETE CASCADE,
    record_id BIGINT NOT NULL REFERENCES community_records(id) ON DELETE CASCADE,
    revision INT NOT NULL,
    PRIMARY KEY (resident_id, record_id)
);
